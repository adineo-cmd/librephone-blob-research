import json
import os
import re
import sys

src, outdir = sys.argv[1], sys.argv[2]
os.makedirs(outdir, exist_ok=True)
d = json.load(open(src))
pdev = d["pdev_jump_table"]["map"]
stats = d["stats_jump_table"]["map"]
assert d["pdev_jump_table"]["entries"] == len(pdev) == 85
assert d["stats_jump_table"]["entries"] == len(stats) == 16


def cstr(s):
    return s.replace("\\", "\\\\").replace('"', '\\"')


L = []
L.append("/* Clean-room, spec-derived data table: generated by gen_wmi_tables.py from the")
L.append("   lab's committed F-29 dispatch map (open-discovery-lab, track-a-android-blobs,")
L.append("   results/wmi-pdev-dispatch-map.json). Derived metadata only: event IDs, handler")
L.append("   block addresses, routing flags. No proprietary binary content. */")
L.append("#ifndef WMI_DISPATCH_TABLES_H")
L.append("#define WMI_DISPATCH_TABLES_H")
L.append("")
L.append("#define WMI_PDEV_TABLE_VADDR  0xc056423cu")
L.append("#define WMI_STATS_TABLE_VADDR 0xc05641fcu")
L.append("#define WMI_PDEV_TABLE_LEN    85u")
L.append("#define WMI_STATS_TABLE_LEN   16u")
L.append("#define WMI_SHARED_EXIT_BLOCK 0xc02cedccu")
L.append("#define WMI_SHARED_EXIT_JUMP  0xc04e61a8u")
L.append("")
L.append("typedef struct wmi_table_entry {")
L.append("    unsigned int id;")
L.append("    const char *name;")
L.append("    unsigned int handler;")
L.append("    int handled;")
L.append("    int registry_record;")
L.append("} wmi_table_entry_t;")
L.append("")
L.append("static const wmi_table_entry_t wmi_pdev_table[WMI_PDEV_TABLE_LEN] = {")
for e in pdev:
    nm = e["ath11k_name"] or "(fw-specific)"
    L.append('    {0x%04xu, "%s", 0x%08xu, %d, %d},' % (
        int(e["id"], 16), cstr(nm), int(e["handler"], 16),
        1 if e["handled"] else 0, 1 if e["registry_record"] else 0))
L.append("};")
L.append("")
L.append("static const wmi_table_entry_t wmi_stats_table[WMI_STATS_TABLE_LEN] = {")
for e in stats:
    nm = e["ath11k_name"] or "(fw-specific)"
    L.append('    {0x%04xu, "%s", 0x%08xu, %d, %d},' % (
        int(e["id"], 16), cstr(nm), int(e["handler"], 16),
        1 if e["handled"] else 0, 1 if e["registry_record"] else 0))
L.append("};")
L.append("")

cmp_entries = []
for e in d["misc_cmp_tree"]:
    blk = e["block"]
    m = re.match(r"^0x([0-9a-f]+)$", blk)
    if m:
        cmp_entries.append((int(e["id"], 16), e["ath11k_name"] or "(fw-specific)", int(m.group(1), 16), 0))
    else:
        mm = re.search(r"jump\s+0x([0-9a-f]+)", blk)
        assert mm, blk
        cmp_entries.append((int(e["id"], 16), e["ath11k_name"] or "(fw-specific)", int(mm.group(1), 16), 2))

for t in d["top_level_tree"]:
    mech = t["mechanism"]
    if t["group"].startswith("VDEV"):
        mm = re.search(r"tail-jump\s+0x([0-9a-f]+)", mech)
        cmp_entries.append((0x5022, "(fw-specific)", int(mm.group(1), 16), 0))
    elif t["group"].startswith("SUSPEND"):
        cmp_entries.append((0x11001, "WMI_PDEV_RESUME_EVENTID", 0, 1))
        mm = re.search(r"call\s+0x([0-9a-f]+)", mech.split("0x2->")[1])
        cmp_entries.append((0x11002, "(fw-specific)", int(mm.group(1), 16), 2))
    elif t["group"].startswith("GPIO"):
        cmp_entries.append((0x1e001, "WMI_GPIO_INPUT_EVENTID", 0, 1))
        cmp_entries.append((0x1e002, "WMI_UPLOADH_EVENTID", 0, 1))

L.append("typedef struct wmi_cmp_entry {")
L.append("    unsigned int id;")
L.append("    const char *name;")
L.append("    unsigned int block;")
L.append("    int kind;")
L.append("} wmi_cmp_entry_t;")
L.append("")
L.append("#define WMI_CMP_KIND_BLOCK   0")
L.append("#define WMI_CMP_KIND_RUNTIME 1")
L.append("#define WMI_CMP_KIND_CALL    2")
L.append("#define WMI_CMP_TREE_LEN     %du" % len(cmp_entries))
L.append("")
L.append("static const wmi_cmp_entry_t wmi_cmp_tree[WMI_CMP_TREE_LEN] = {")
for eid, nm, blk, kind in cmp_entries:
    L.append('    {0x%04xu, "%s", 0x%08xu, %d},' % (eid, cstr(nm), blk, kind))
L.append("};")
L.append("")
L.append("#endif")
open(os.path.join(outdir, "wmi_dispatch_tables.h"), "w").write("\n".join(L) + "\n")
print("pdev_entries", len(pdev), "handled", sum(1 for e in pdev if e["handled"]))
print("stats_entries", len(stats), "handled", sum(1 for e in stats if e["handled"]))
