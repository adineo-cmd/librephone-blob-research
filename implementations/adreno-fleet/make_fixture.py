"""make_fixture.py -- deterministic synthetic fixtures for gmu_probe.py.

CLEAN-ROOM / NO-PROPRIETARY-BYTES STATEMENT
===========================================
Every byte written here is generated by this script from (a) the public GPL
kernel sources named in gmu_probe.py and (b) the structural layout the lab
*measured* on real payloads.  No real microcode byte is copied, embedded or
transcribed anywhere in this file -- not one byte, not one instruction word.
The repo's .gitignore excludes *.bin, so the fixtures are working-tree
artifacts only; regenerating reproduces them byte-for-byte, which
test_gmu_probe.py verifies.

WHY SYNTHETIC
-------------
Two reasons.  First, the program rule: real proprietary payloads never enter
the repo.  Second -- and this matters more for the tests -- a synthetic
fixture lets us assert *exact* expected values (SP, VTOR, block addresses,
descriptor counts) instead of "whatever the vendor shipped", so a parser
regression produces a hard failure rather than a silently-shifted report.

FIXTURES
--------
  a619like_raw.bin          32,768 B  raw ITCM+DTCM image, the a619/a630 shape
                                     (md5 9e23c520... layout). 32-bit
                                     identity-style code stream, 0xbabeface
                                     init magic, region descriptor table,
                                     DTCM address/zero-value table.
  a619like_truncated.bin    16,384 B  raw image cut in half -> legacy-size
                                     violation (error path, exit 1)
  a619like_badsp.bin        32,768 B  raw image with a corrupt initial SP
                                     (error path: SP outside DTCM)
  a640like_container.bin    37,680 B  mainline struct block_header container
                                     with a 6-record zero-size descriptor
                                     table and deadbeef markers -- the
                                     a640/a650/a660 shape
  container_truncated.bin     ~2,000 B mainline chain whose last record
                                     overruns EOF (container rejection path)
  unknown.bin                  512 B  bytes that match neither model
                                     (error path: unrecognised layout)

Sizes deliberately mirror the fleet magnitudes: the raw image is exactly
0x8000 because that is the legacy loader's hard cap (a6xx_gmu.c:896), and
the a640-class container is 37,680 B to match the real a640_gmu.bin size.

Usage:  python3 -I make_fixture.py [--outdir DIR]
"""

import argparse
import hashlib
import os
import struct
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
DEFAULT_OUTDIR = os.path.join(HERE, "fixtures")

# ---------------------------------------------------------------------------
# Layout constants (see gmu_probe.py for the citations)
# ---------------------------------------------------------------------------
ITCM_BASE = 0x00000000
DTCM_BASE = 0x00040000
TCM_SIZE = 0x4000
RAW_IMAGE_SIZE = 0x8000              # a6xx_gmu.c:896 cap == ITCM + DTCM

VTOR_ADDR = 0xE000ED08
FW_INIT_MAGIC = 0xBABEFACE
MARKER = 0xDEADBEEF

# Synthetic build id pair standing in for the measured a619 0x1011/0x3d79.
SYNTH_BUILD = (0x1022, 0x3D90)


def stream(n, tag):
    """Deterministic pseudo-random byte stream: SHA-256 of a tagged counter.

    Used for payload fill so that unrelated fixtures never share bytes, and
    so regeneration is exact."""
    tag = tag.encode() if isinstance(tag, str) else tag
    out = bytearray()
    counter = 0
    while len(out) < n:
        out += hashlib.sha256(b"gmu:%s:%d" % (tag, counter)).digest()
        counter += 1
    return bytes(out[:n])


# ---------------------------------------------------------------------------
# A tiny Thumb-2 assembler for the handful of encodings the probe recognises.
#
# The probe's census counts 16-bit encodings by exact bit pattern; the
# startup stub check reads 32-bit `msr` forms.  Emitting those patterns
# directly is both simpler and more honest than pretending to assemble
# arbitrary code.  All encodings below are from the ARMv7-M ARM.
# ---------------------------------------------------------------------------

def thumb_ldr_pc(rd, imm8_units):
    """ldr Rt,[pc,#imm8*4]  --  0100 1 Rt:3 imm8   (imm8 is in words)."""
    assert 0 <= rd <= 7 and 0 <= imm8_units <= 0xFF
    return struct.pack("<H", 0x4800 | (rd << 8) | imm8_units)


def thumb_ldr_pc_hi(rd, imm8_units):
    """`ldr Rt,[pc,#imm8*4]` with Rt >= 8 -- 0100 1 Rt imm8 covers Rt:4."""
    assert 8 <= rd <= 15 and 0 <= imm8_units <= 0xFF
    return struct.pack("<H", 0x4800 | (rd << 8) | imm8_units)


def thumb_msr_sp(which):
    """msr msp|psp, r0  --  f380 8808 | f380 8809 (32-bit Thumb-2)."""
    return struct.pack("<HH", 0xF380, 0x8808 if which == "msp" else 0x8809)


def thumb_str_imm(rt, rn, imm5_words):
    """str Rt,[Rn,#imm5*4]  --  0110 0 imm5 Rn Rt."""
    assert 0 <= imm5_words <= 31
    return struct.pack("<H", 0x6000 | (imm5_words << 6) | (rn << 3) | rt)


def thumb_nop():
    return struct.pack("<H", 0xBF00)


def thumb_b_dot():
    """b .   -- e7fe, the classic `while (1)`."""
    return struct.pack("<H", 0xE7FE)


def thumb_bx_lr():
    return struct.pack("<H", 0x4770)


def thumb_bw(insn_off, target):
    """b.w T4 -- f000 bxxx / f000 9xxx pair.

    Encoded from the ARMv7-M ARM B.T4 definition so the probe's expectation
    (and any future T4 decode) agree with what we wrote."""
    imm = target - (insn_off + 4)
    assert -(1 << 24) <= imm < (1 << 24)
    s = 1 if imm < 0 else 0
    u = imm & 0x1FFFFFF if imm >= 0 else (imm + (1 << 25)) & 0x1FFFFFF
    i1 = (u >> 23) & 1
    i2 = (u >> 22) & 1
    imm10 = (u >> 12) & 0x3FF
    imm11 = (u >> 1) & 0x7FF
    j1 = (1 - (i1 ^ s)) & 1
    j2 = (1 - (i2 ^ s)) & 1
    hw1 = 0xF000 | (s << 10) | imm10
    hw2 = 0x9000 | (j1 << 13) | (j2 << 11) | imm11
    return struct.pack("<HH", hw1, hw2)


# ---------------------------------------------------------------------------
# Raw ITCM+DTCM image
# ---------------------------------------------------------------------------

def make_raw_image(tag="a619like", total=RAW_IMAGE_SIZE,
                   sp=None, build=SYNTH_BUILD):
    """Build a raw ITCM+DTCM image with the measured layout.

    Region map (file offsets; see gmu-analysis.md section 3):
        0x0000  u32 initial SP      (and the vector table copies it)
        0x0004  u32 Reset vector    (Thumb bit set, points into ITCM)
        0x0008  reset stub: load SP/PSP, set VTOR, branch to 0x400
        0x0020  literals used by the stub
        0x0200  Cortex-M vector table (16 architectural + 64 external IRQ)
        0x0240  code: synthetic Thumb-2 stream with the census patterns
        0x3EA4  region descriptor table (8 ascending {start,end} pairs)
        0x4000  DTCM: build id pair, small config words, address table
    """
    img = bytearray(b"\x00" * total)

    if sp is None:
        sp = DTCM_BASE + TCM_SIZE - 0x80          # top - 0x80
    psp = DTCM_BASE + 0x1440                      # DTCM + 0x1440
    vt_off = 0x200

    # --- reset stub at 0x08 (the exact shape the probe recognises) ---------
    stub = bytearray()
    stub += thumb_ldr_pc(0, 5)                    # 0x08 ldr r0,[pc,#20]->0x20
    stub += thumb_msr_sp("msp")                   # 0x0a
    stub += thumb_ldr_pc(0, 5)                    # 0x0e ldr r0,[pc,#20]->0x24
    stub += thumb_msr_sp("psp")                   # 0x10
    stub += thumb_ldr_pc(0, 4)                    # 0x14 ldr r0,[pc,#16]->0x28
    stub += thumb_ldr_pc_hi(9, 5)                 # 0x16 ldr r1,[pc,#20]->0x2c
    stub += thumb_str_imm(0, 1, 0)                # 0x18 str r0,[r1,#0]
    stub += thumb_bw(0x1A, 0x400)                 # 0x1a b.w 0x400
    stub += thumb_nop()                           # 0x1e
    assert len(stub) == 0x18, len(stub)
    img[0x08:0x08 + len(stub)] = stub

    # --- literals at 0x20 --------------------------------------------------
    struct.pack_into("<IIII", img, 0x20, sp, psp, vt_off, VTOR_ADDR)
    struct.pack_into("<II", img, 0x00, sp, 0x09)  # SP + Reset (Thumb)

    # --- vector table at 0x200 --------------------------------------------
    # 16 architectural vectors.  Handlers point at small stubs in ITCM; the
    # Reset entry repeats the 0x09 the core loads.
    # Indices follow ARM DDI 0403's vector table order exactly:
    #   0 SP, 1 Reset, 2 NMI, 3 HardFault, 4 MemManage, 5 BusFault,
    #   6 UsageFault, 7-10 reserved, 11 SVCall, 12 DebugMonitor,
    #   13 reserved, 14 PendSV, 15 SysTick
    vt = [
        sp, 0x09,          # 0 initial SP, 1 Reset
        0x81, 0x51, 0x71, 0x31, 0xC1,   # 2 NMI .. 6 UsageFault
        0, 0, 0, 0,        # 7-10 reserved
        0xA1,              # 11 SVCall
        0x41,              # 12 DebugMonitor
        0,                 # 13 reserved
        0x91,              # 14 PendSV
        0xB1,              # 15 SysTick
    ]
    assert len(vt) == 16, len(vt)
    # 64 external interrupts, all collapsing on one shared handler (measured
    # behaviour of the real image; a single target is what the probe reports).
    vt += [0x61] * 64
    struct.pack_into("<%dI" % len(vt), img, vt_off, *vt)

    # --- trap handler stubs at 0x30..0xC8 ---------------------------------
    # Each stub is: ldr r0,[pc,#0]; ldr r1,[r0,#0]; adds r1,#1; str r1,[r0,#0]
    #               b .; <literal pointing at a DTCM counter>
    counter_base = DTCM_BASE + 0x1200
    for i in range(10):
        off = 0x30 + i * 0x10
        struct.pack_into("<H", img, off + 0, 0x4802)          # ldr r0,[pc,#8]
        struct.pack_into("<H", img, off + 2, 0x6901)          # ldr r1,[r0,#0x10]
        struct.pack_into("<H", img, off + 4, 0x1C49)          # adds r1,#1
        struct.pack_into("<H", img, off + 6, 0x6101)          # str r1,[r0,#0x10]
        img[off + 8:off + 10] = thumb_b_dot()
        struct.pack_into("<I", img, off + 12, counter_base)

    # --- code body 0x340..0x3EA4 ------------------------------------------
    # NB: starts at 0x340, not 0x240 -- the vector table's 64 external
    # interrupt entries occupy 0x240..0x340.
    body_lo, body_hi = 0x340, 0x3EA4
    fill = bytearray(stream(body_hi - body_lo, tag + ":code"))
    i = 0

    def emit(off, blob):
        nonlocal i
        need = off + len(blob) - body_lo
        while len(fill) < need:
            i += 1
            fill.extend(stream(256, "%s:code:%d" % (tag, i)))
        fill[off - body_lo:off - body_lo + len(blob)] = blob

    off = body_lo
    # A per-tag jitter keeps the emitted operand bytes tag-dependent, so two
    # fixtures built from different tags never share a code body.  Structure
    # (prologue/epilogue/call shapes) stays identical, which is what the
    # census assertions need.
    jitter = int(hashlib.sha256(("%s:jitter" % tag).encode()).hexdigest()[:8], 16)
    while off < body_hi - 0x20:
        # function prologue
        emit(off, struct.pack("<H", 0xB510 | (off % 8)))       # push {r4,lr}
        emit(off + 2, thumb_ldr_pc(0, ((0x1000 - (off + 4)) // 4) & 0xFF))
        emit(off + 4, struct.pack("<H", 0x2000 | ((off + jitter) % 0x100)))
        emit(off + 6, struct.pack("<H", 0x6800 | ((off // 4) % 8)))
        emit(off + 8, struct.pack("<HH", 0xF000,
                                  0xF800 | ((off + jitter) % 0x100)))  # bl
        emit(off + 12, struct.pack("<H", 0x6000 | ((off // 4) % 8)))     # str
        emit(off + 14, struct.pack("<H", 0xD100 | ((off + jitter) % 0x100)))
        emit(off + 16, thumb_bx_lr())
        emit(off + 18, thumb_nop())
        off += 0x20

    # Plant the firmware-init magic twice, as the real image does.  Absolute
    # file offsets are chosen to sit inside the code body and are asserted
    # against in the test suite.
    MAGIC_SITES = (0x1AF4, 0x2EC8)
    for site in MAGIC_SITES:
        struct.pack_into("<I", fill, site - body_lo, FW_INIT_MAGIC)
    img[body_lo:body_hi] = fill[:body_hi - body_lo]

    # --- region descriptor table at 0x3EA4 --------------------------------
    # 8 ascending {start,end} pairs alternating DTCM/ITCM, as measured.
    desc = [
        (DTCM_BASE + 0x06CC, DTCM_BASE + 0x2000),
        (ITCM_BASE + 0x0404, ITCM_BASE + 0x043C),
        (DTCM_BASE + 0x0000, DTCM_BASE + 0x1200),
        (ITCM_BASE + 0x0244, ITCM_BASE + 0x0458),
        (DTCM_BASE + 0x06CC, DTCM_BASE + 0x1E00),
        (ITCM_BASE + 0x016C, ITCM_BASE + 0x0458),
        (DTCM_BASE + 0x0AD0, DTCM_BASE + 0x3F80),
        (ITCM_BASE + 0x0004, ITCM_BASE + 0x0458),
    ]
    p = 0x3EA4
    for a, b in desc:
        struct.pack_into("<II", img, p, a, b)
        p += 8
    assert p == 0x3EE4

    # --- DTCM half ---------------------------------------------------------
    if total >= TCM_SIZE + 0x10:
        # byte 0x4002 = build id halfwords (measured pair position)
        struct.pack_into("<HH", img, TCM_SIZE + 2, *build)
        # config words
        struct.pack_into("<I", img, TCM_SIZE + 0x40, 0xE0E00000)
        for k in range(6):
            struct.pack_into("<I", img, TCM_SIZE + 0x60 + 4 * k, 0x64)
        struct.pack_into("<II", img, TCM_SIZE + 0x88, 0x44091054, 0x44091008)
        struct.pack_into("<I", img, TCM_SIZE + 0x98, 1)
        struct.pack_into("<II", img, TCM_SIZE + 0xA0, 0x44091118, 0x44091110)

        # stride-8 {address, 0} table in the 0x44000000 window
        tbl = TCM_SIZE + 0x4D8
        addrs = [0x440020C0, 0x440020C4, 0x44021800, 0x440218AC, 0x440218A8,
                 0x440218A4, 0x440218A0, 0x44034008, 0x4402F810, 0x44027800]
        q = tbl
        for k in range(10):
            struct.pack_into("<II", img, q, addrs[k % len(addrs)], 0)
            q += 8

    return bytes(img)


def make_raw_truncated(tag="trunc"):
    """Half an image: violates the legacy loader's 0x8000 cap."""
    full = make_raw_image(tag + ":full")
    return full[:RAW_IMAGE_SIZE // 2]


def make_raw_bad_sp(tag="badsp"):
    """Image whose initial SP points outside DTCM (error path)."""
    return make_raw_image(tag, sp=0x00012340)


# ---------------------------------------------------------------------------
# Mainline struct block_header container (the a640/a650/a660/a623/a663 shape)
# ---------------------------------------------------------------------------

def make_container(tag="a640like", total=37680):
    """Build a container that mainline's walker parses to EXACT EOF.

    Structure:
        [0x000, 0x060)  6 zero-size descriptor records {addr, 0, type=1, value}
        [0x060, 0x070)  deadbeef marker record (size 0)
        then payload blocks, each 16-byte header + `size` bytes of data.

    The descriptors deliberately alternate a TCM base with a length value,
    mirroring what the real a623/a650/a660 tables look like.
    """
    head = bytearray()
    descs = [
        (0x00000000, 0x000001DC),
        (0x00004000, 0x0000D000),
        (0x00000200, 0x00003A00),
        (0x00100000, 0x00008000),
        (0x00200000, 0x00012000),
        (0x00300000, 0x00014000),
    ]
    for addr, val in descs:
        head += struct.pack("<IIII", addr, 0, 1, val)
    head += struct.pack("<IIII", 0, 0, MARKER, MARKER)

    # Payload blocks: (load addr, size).  Addresses mirror the real a640
    # container's measured block plan exactly: 0x0 (ITCM), 0x4000, 0x40000
    # (DTCM) and 0x57000 (a BO-mapped region, a6xx_gmu.c:923-926).
    blocks = [
        [0x00000000, 0x00000030],
        [0x00000200, 0x00000140],
        [0x00000400, 0x000038BC],
        [0x00004000, 0x00003A58],
        [0x00040000, 0x00001B20],
        [0x00043FE0, 0x00000014],
        [0x00057000, 0x00000308],
    ]
    # Solve the last block's size so len(head) + sum(16+size) == total.
    fixed = len(head) + 16 * len(blocks) + sum(b[1] for b in blocks[:-1])
    blocks[-1][1] = total - fixed
    if blocks[-1][1] <= 0:
        raise AssertionError("requested size too small for this block plan")

    body = bytearray()
    for i, (addr, size) in enumerate(blocks):
        body += struct.pack("<IIII", addr, size, MARKER, MARKER)
        body += stream(size, "%s:blk%d" % (tag, i))

    out = bytes(head) + bytes(body)
    if len(out) != total:
        raise AssertionError("container size %d != %d" % (len(out), total))
    return out


def make_container_truncated(tag="ctrunc"):
    """A container whose last record declares more bytes than remain."""
    out = bytearray()
    out += struct.pack("<IIII", 0, 0, MARKER, MARKER)
    out += struct.pack("<IIII", 0x00000000, 0x100, MARKER, MARKER)
    out += stream(0x100, tag + ":b0")
    out += struct.pack("<IIII", 0x00004000, 0x400, MARKER, MARKER)
    out += stream(0x40, tag + ":b1")          # only 0x40 of the declared 0x400
    return bytes(out)


def make_unknown(tag="unknown"):
    """Neither model: no ARMv7-M stub, no valid block chain."""
    return stream(512, tag)


# ---------------------------------------------------------------------------
# main
# ---------------------------------------------------------------------------

def build_all():
    return [
        ("a619like_raw.bin", make_raw_image()),
        ("a619like_truncated.bin", make_raw_truncated()),
        ("a619like_badsp.bin", make_raw_bad_sp()),
        ("a640like_container.bin", make_container()),
        ("container_truncated.bin", make_container_truncated()),
        ("unknown.bin", make_unknown()),
    ]


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--outdir", default=DEFAULT_OUTDIR)
    args = ap.parse_args(argv)

    os.makedirs(args.outdir, exist_ok=True)
    rows = []
    for name, blob in build_all():
        path = os.path.join(args.outdir, name)
        with open(path, "wb") as f:
            f.write(blob)
        rows.append((name, len(blob), hashlib.md5(blob).hexdigest(),
                     hashlib.sha256(blob).hexdigest()))

    width = max(len(r[0]) for r in rows)
    for name, n, md5, _ in rows:
        print("%-*s %8d B  md5 %s" % (width, name, n, md5))
    print()
    print("All fixtures are synthetic: generated by this script from the public")
    print("layout only. Regeneration is byte-identical (test_gmu_probe verifies).")
    print("Sizes mirror the fleet: raw image = 0x8000 (the legacy loader cap,")
    print("a6xx_gmu.c:896); a640-class container = 37,680 B (real a640_gmu.bin).")
    return 0


if __name__ == "__main__":
    sys.exit(main())
