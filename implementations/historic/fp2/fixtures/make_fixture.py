#!/usr/bin/env python3
"""make_fixture.py — build SYNTHETIC fixtures for the clean-room parsers in
this directory (mdt_probe.py, prima_nv_probe.py).

======================================================================
CLEAN-ROOM STATEMENT
All fixtures are SYNTHETIC: every byte is generated by this script from
the public format rules (see the parsers' headers for their sources).
No real firmware payload bytes are used, embedded or reproduced.
======================================================================

Generated fixtures (written next to this script):
  synth_modem.mdt / synth_modem.b00 / synth_modem.b01 / synth_modem.b02
      a minimal split image: phdr0 = metadata (ehdr+phdr table extent),
      phdr1 = hash segment, phdr2 = one 4052-byte loadable segment
      at 0x08000000 (sizes mirror the FP2 modem layout shape, contents
      synthetic LCG bytes).
  synth_nv3.bin
      an NV3 template-stream image: CAFEBABE magic + table-of-tables +
      one table template + one data stream (u16-length framing).
  synth_nv2.bin
      an NV2 raw packed struct image: validity bitmap + sNvFields identity
      block + a padding tables block.

Usage: python3 -I make_fixture.py [OUTDIR]
"""

import os
import struct
import sys

EHDR_SIZE = 52
PHDR_SIZE = 32


def lcg(seed, n):
    """Deterministic synthetic payload bytes (never taken from any real
    firmware)."""
    out = bytearray()
    x = seed
    for _ in range(n):
        x = (x * 1103515245 + 12345) & 0x7FFFFFFF
        out.append((x >> 16) & 0xFF)
    return bytes(out)


def phdr(p_type, p_offset, p_vaddr, p_paddr, p_filesz, p_memsz, p_flags, p_align):
    return struct.pack("<8I", p_type, p_offset, p_vaddr, p_paddr,
                       p_filesz, p_memsz, p_flags, p_align)


def make_mdt(outdir):
    # layout mirrors the FP2 modem.mdt SHAPE (metadata phdr + hash phdr +
    # one loadable), with synthetic contents.
    meta_filesz = EHDR_SIZE + 2 * PHDR_SIZE + 764   # arbitrary metadata tail
    hash_filesz = 904
    seg_filesz = 4052
    phdrs = [
        # 0: metadata: PT_NULL with type bits 7 (0x07000000), filesz covers
        #    ehdr + phdr table + metadata bytes
        phdr(0, 0, 0, 0, meta_filesz, 0, 0x07000000, 0),
        # 1: hash segment: PT_NULL, TYPE_HASH = 2<<24, memsz 4096
        phdr(0, 4096, 0x0D100000, 0x0D100000, hash_filesz, 4096, 0x02200000, 4096),
        # 2: loadable segment at 0x08000000, RXW
        phdr(1, 8192, 0x08000000, 0x08000000, seg_filesz, seg_filesz, 5, 4096),
    ]
    ehdr = struct.pack("<4s5B7x2H5I6H", b"\x7fELF", 1, 1, 1, 0, 0,
                       2, 164, 1, 0x08000000, EHDR_SIZE, 0, 0,
                       EHDR_SIZE, PHDR_SIZE, len(phdrs), 0, 0, 0)
    metadata_tail = lcg(1, meta_filesz - EHDR_SIZE - len(phdrs) * PHDR_SIZE)
    hash_body = lcg(2, hash_filesz)
    seg_body = lcg(3, seg_filesz)
    mdt = ehdr + b"".join(phdrs) + metadata_tail
    with open(os.path.join(outdir, "synth_modem.mdt"), "wb") as f:
        f.write(mdt)
    # the loader expects b00 = phdr0 extent (metadata), b01 = hash, b02 = seg
    with open(os.path.join(outdir, "synth_modem.b00"), "wb") as f:
        f.write(lcg(1, meta_filesz))
    with open(os.path.join(outdir, "synth_modem.b01"), "wb") as f:
        f.write(hash_body)
    with open(os.path.join(outdir, "synth_modem.b02"), "wb") as f:
        f.write(seg_body)


def make_nv3(outdir):
    # stream framing: [u16 LE len][bytes]
    def stream(payload):
        return struct.pack("<H", len(payload)) + payload

    table_of_tables = bytes([0x80 | 0x40, 0x00]) + (
        b"AA" + bytes([0x01, 0x00]) +            # name, fieldId=1 (table), SINGULAR
        b"BB" + bytes([0x02, 0x00]) +
        b"CC" + bytes([0x03, 0x00]))
    tbl_template = bytes([0x80 | 0x40, 0x01]) + (
        b"AA" + bytes([0x01, 0x00]) +
        b"BB" + bytes([0x02, 0x00]) +
        b"CC" + bytes([0x03, 0x00]))
    data = bytes([0x00, 0x01]) + b"\x01\x02\x03\x04"  # data stream for table 1
    body = (stream(table_of_tables) + stream(tbl_template) + stream(data))
    with open(os.path.join(outdir, "synth_nv3.bin"), "wb") as f:
        f.write(struct.pack("<I", 0xFFFFFFFF) + struct.pack("<I", 0xCAFEBABE) + body)


def make_nv2(outdir):
    snv = bytearray(72)
    struct.pack_into("<H", snv, 0, 0x1234)          # productId
    snv[2] = 1                                      # productBands = 11A/B/G
    snv[3] = 2                                      # wlanNvRevId = WCN36xx class
    snv[4] = 2                                      # tx chains
    snv[5] = 2                                      # rx chains
    snv[6:12] = b"\x02\x00\x5e\x01\x02\x03"         # macAddr (synthetic)
    snv[30:70] = b"\x00" * 40                       # mfgSN
    snv[70] = 0                                     # couplerType = INTERNAL
    snv[71] = 2                                     # nvVersion = LPDC (Pronto)
    tables = b"\x5a" * 128                          # synthetic tables block
    with open(os.path.join(outdir, "synth_nv2.bin"), "wb") as f:
        f.write(struct.pack("<I", 0xFFFFFFFF) + bytes(snv) + tables)


def main():
    outdir = sys.argv[1] if len(sys.argv) > 1 else os.path.dirname(os.path.abspath(__file__))
    make_mdt(outdir)
    make_nv3(outdir)
    make_nv2(outdir)
    for f in sorted(os.listdir(outdir)):
        print(f, os.path.getsize(os.path.join(outdir, f)))


if __name__ == "__main__":
    main()
