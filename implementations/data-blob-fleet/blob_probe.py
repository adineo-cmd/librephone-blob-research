"""blob_probe.py -- clean-room structural analyser for opaque data blobs.

CLEAN-ROOM / NO-PROPRIETARY-BYTES STATEMENT
===========================================
This program was written from (a) public, freely licensed sources and (b) the
author's own measurements of payload bytes obtained from public repositories.
No decompiled code, no disassembler output, no proprietary header, no vendor
documentation and no vendor tool was read at any point.  Every fact this tool
reports about a real file is either a direct measurement of the bytes on disk
(arithmetic, histograms, entropy, equality) or a value quoted from a public
source named in `data-blob-analysis.md`.

The tool is deliberately format-agnostic: it asserts no structure it has not
measured.  It answers "what shapes are present in these bytes?" -- header
probe, size factorisation, record-stride autocorrelation, integer/float
plausibility, block entropy, printable strings, same-offset diff -- and leaves
the interpretation to the analyst.

No proprietary payload is bundled with or produced by this file.  The
`fixtures/` directory holds synthetic bytes generated by `make_fixture.py`
from the layouts documented in public sources; the repo's .gitignore excludes
`*.bin`, so fixtures are working-tree artifacts regenerated on demand.

WHY THESE PASSES
----------------
The leverage question behind the fleet is always the same: *is this file a
coefficient table for a format somebody has already specified publicly, or is
it an opaque vendor container?*  Three cheap measurements separate most cases:

  * size factorisation against a documented grid (e.g. taps x directions x
    ears x bytes-per-sample);
  * float plausibility -- a filter-coefficient table read as IEEE-754 binary32
    produces finite values in a narrow physical range, an integer/tag file
    produces denormals and astronomically large "floats";
  * record-stride autocorrelation -- a packed table repeats at a fixed stride,
    a container repeats at tag boundaries.

None of the three is conclusive alone.  The report keeps them separate and
prints the raw numbers so a reader can disagree with the conclusion.

USAGE
-----
    python3 -I blob_probe.py <file> [--json out.json] [--brief] [--floats]
                                [--diff other.bin] [--max-stride N]
                                [--strings-min N] [--blocks N]

Exit status: 0 on success, 2 on unreadable input or bad arguments.  This tool
does not validate anything, so it never exits 1 on content.

Pure stdlib.  Python 3.8+.
"""

