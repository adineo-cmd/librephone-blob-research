# ---------------------------------------------------------------------------
# small helpers
# ---------------------------------------------------------------------------

PRINTABLE_RUN = re.compile(rb"[\x20-\x7e]{2,}")


def shannon_entropy(buf):
    """Shannon entropy in bits/byte of `buf` (0.0 for empty input)."""
    if not buf:
        return 0.0
    counts = collections.Counter(buf)
    n = len(buf)
    return -sum((c / n) * math.log2(c / n) for c in counts.values())


def factorize(n):
    """Prime factorisation of a positive integer -> {prime: exponent}."""
    if n < 1:
        return {}
    out = {}
    m = n
    p = 2
    while p * p <= m:
        while m % p == 0:
            out[p] = out.get(p, 0) + 1
            m //= p
        p += 1 if p == 2 else 2
    if m > 1:
        out[m] = out.get(m, 0) + 1
    return out


def factor_string(n):
    """'164480 = 2^7 x 5 x 257' style rendering."""
    f = factorize(n)
    if not f:
        return str(n)
    parts = []
    for p in sorted(f):
        parts.append(str(p) if f[p] == 1 else "%d^%d" % (p, f[p]))
    return " x ".join(parts)


def divisors(n):
    """All positive divisors of n, ascending."""
    ds = []
    i = 1
    while i * i <= n:
        if n % i == 0:
            ds.append(i)
            if i != n // i:
                ds.append(n // i)
        i += 1
    return sorted(ds)


def grid_decompositions(size, per_sample_bytes=(2, 4), max_terms=3):
    """Enumerate `size = a * b * c * ...` splits over the size's divisors.

    Returns every ordered tuple of `max_terms` factors > 1 (recursively, so
    tuples shorter than max_terms are included too) plus, for each tuple, the
    per-sample byte widths that divide evenly.  The caller supplies the
    candidate widths -- 2 and 4 are the realistic ones for audio coefficients,
    4 for float tables.

    This is arithmetic only: a decomposition is *admissible*, never *proven*.
    """
    out = []
    divs = [d for d in divisors(size) if d > 1]

    def walk(prefix, rest, depth):
        if prefix:
            widths = [w for w in per_sample_bytes if rest % w == 0]
            out.append({"factors": list(prefix), "remainder": rest,
                        "widths": widths})
        if depth == 0:
            return
        for d in divs:
            if d > rest:
                break
            if rest % d:
                continue
            # keep non-decreasing to avoid permutations of the same split
            if prefix and d < prefix[-1]:
                continue
            walk(prefix + [d], rest // d, depth - 1)

    walk([], size, max_terms)
    # de-duplicate on (tuple, remainder)
    seen = set()
    uniq = []
    for rec in out:
        key = (tuple(rec["factors"]), rec["remainder"])
        if key in seen:
            continue
        seen.add(key)
        uniq.append(rec)
    return uniq


# ---------------------------------------------------------------------------
# pass 1: header probe
# ---------------------------------------------------------------------------

MAGIC_HINTS = (
    (b"\x89HDF\r\n\x1a\n", "HDF5 (the container SOFA/AES69 files are stored in)"),
    (b"CDF\x01", "NetCDF classic (SOFA's older storage form)"),
    (b"MinPHR", "OpenAL Soft HRTF data set"),
    (b"RIFF", "RIFF container"),
    (b"\x7fELF", "ELF"),
    (b"VER0", "4CC tag table beginning with VER0"),
    (b"ENDM", "4CC tag stream terminator"),
)


def probe_header(buf, n=64):
    """Report the first `n` bytes as hex/ASCII plus structural hints.

    Deliberately shallow: this pass reports what is *there* (printable 4CC
    tags, integer fields at several widths, a known public magic if one
    matches) and never claims a version or a record count.
    """
    head = buf[:n]
    hints = []
    for magic, label in MAGIC_HINTS:
        if head.startswith(magic) or (len(magic) > 8 and magic in head):
            hints.append(label)

    # 4-character-code sweep over the first KiB -- catches tag containers
    fourcc = []
    for m in re.finditer(rb"[A-Z][A-Z0-9]{3}", buf[:1024]):
        fourcc.append({"offset": m.start(), "tag": m.group().decode("ascii")})

    # little/big-endian 32-bit reads of the first 6 words
    words_le = []
    words_be = []
    for i in range(0, min(len(buf), 24), 4):
        chunk = buf[i:i + 4]
        if len(chunk) < 4:
            break
        words_le.append(struct.unpack("<I", chunk)[0])
        words_be.append(struct.unpack(">I", chunk)[0])

    # does the file start with a plausible little-endian count table?
    ascii_prefix = sum(1 for b in head if 0x20 <= b < 0x7F)
    return {
        "first_bytes_hex": head[:32].hex(" "),
        "first_bytes_ascii": "".join(chr(b) if 0x20 <= b < 0x7F else "." for b in head),
        "printable_fraction_in_header": round(ascii_prefix / max(1, len(head)), 4),
        "magic_hints": hints,
        "fourcc_first_kib": fourcc[:32],
        "u32_le_first6": words_le,
        "u32_be_first6": words_be,
    }


# ---------------------------------------------------------------------------
# pass 2: record-stride autocorrelation
# ---------------------------------------------------------------------------

def detect_stride(buf, max_stride=256, top=8):
    """Rank candidate record strides by self-similarity.

    Two independent measures, both O(len(buf) * max_stride):

      * `byte_eq[s]`  -- fraction of positions i where buf[i] == buf[i+s].
        A record stride with any repeated field lifts this well above the
        1/256 chance baseline; a packed table of distinct floats does not,
        which is itself informative.
      * `word4_eq[s]` -- fraction of 4-byte words equal to the word s bytes
        later.  Spikes when a fixed-size record carries repeated 32-bit
        fields (tags, lengths, zero padding).

    The reported `best` is the argmax of `byte_eq` restricted to strides that
    divide the file length, because a true record stride must tile the file.
    """
    n = len(buf)
    results = []
    limit = min(max_stride, max(1, n // 2))
    for s in range(2, limit + 1):
        same_bytes = sum(1 for i in range(n - s) if buf[i] == buf[i + s])
        byte_eq = same_bytes / (n - s)
        # 4-byte word equality, aligned
        nw = (n - s) // 4
        if nw > 0:
            wa = buf[:nw * 4]
            wb = buf[s:s + nw * 4]
            same_w = sum(1 for i in range(0, nw * 4, 4) if wa[i:i + 4] == wb[i:i + 4])
            word_eq = same_w / nw
        else:
            word_eq = 0.0
        results.append({"stride": s, "byte_eq": round(byte_eq, 4),
                        "word4_eq": round(word_eq, 4),
                        "divides_length": (n % s == 0)})

    by_byte = sorted(results, key=lambda r: -r["byte_eq"])[:top]
    by_word = sorted(results, key=lambda r: -r["word4_eq"])[:top]

    # A stride s and every multiple of s are equally self-similar, so the
    # fundamental period is the *smallest* stride that is (near-)maximal.
    # Reporting the largest instead would always return the file length.
    tiling = [r for r in results if r["divides_length"]]
    best = None
    if tiling:
        peak = max(r["byte_eq"] for r in tiling)
        if peak > 0.0:
            near = [r for r in tiling if r["byte_eq"] >= peak * 0.98]
            best = min(near, key=lambda r: r["stride"])

    return {
        "max_stride_probed": limit,
        "baseline_byte_eq": round(1.0 / 256.0, 6),
        "top_by_byte_equality": by_byte,
        "top_by_word4_equality": by_word,
        "best_tiling_stride": best,
    }


def stride_flag_profile(buf, stride, width=4):
    """For a candidate stride, report where 4-byte 'tags' sit inside it.

    A tag-record container shows a spike at one offset-within-record; a packed
    coefficient table shows none.  `width` is the field width tested.
    """
    if stride <= 0:
        return {}
    n = len(buf)
    hits = collections.Counter()
    total = 0
    for off in range(0, n - width + 1, width):
        chunk = buf[off:off + width]
        core = chunk.rstrip(b"\x00")
        if 3 <= len(core) <= 4 and all(97 <= c <= 122 for c in core):
            hits[off % stride] += 1
        total += 1
    return {"stride": stride, "width": width,
            "hits_by_phase": sorted(hits.items()), "positions_scanned": total}


