def block_entropy(buf, blocks=16):
    """Entropy per block, so a header/code/data split shows as a shape change.

    A flat profile means homogeneous content (a packed coefficient table).  A
    profile that falls off at the tail means trailing padding or a low-entropy
    string/tag region.
    """
    if blocks < 1:
        blocks = 1
    n = len(buf)
    if n == 0:
        return {"blocks": 0, "profile": [], "overall": 0.0}
    size = max(1, n // blocks)
    profile = []
    for i in range(blocks):
        start = i * size
        end = n if i == blocks - 1 else (i + 1) * size
        chunk = buf[start:end]
        profile.append({"index": i, "start": start, "end": end,
                        "entropy": round(shannon_entropy(chunk), 3),
                        "zero_fraction": round(chunk.count(0) / max(1, len(chunk)), 4)})
    return {
        "blocks": blocks,
        "block_size": size,
        "overall": round(shannon_entropy(buf), 3),
        "profile": profile,
        "shape": _entropy_shape([p["entropy"] for p in profile]),
    }


def _entropy_shape(values):
    """Coarse label for the entropy profile (never a format claim)."""
    if not values:
        return "empty"
    lo, hi = min(values), max(values)
    spread = hi - lo
    if spread < 0.25:
        return "flat"
    if values[-1] < values[0] - 0.5:
        return "falling-tail"
    if values[0] < values[-1] - 0.5:
        return "rising-head"
    return "mixed"


