# pass 5: strings
# ---------------------------------------------------------------------------

def extract_strings(buf, min_len=4, limit=200):
    """Printable ASCII runs of at least `min_len` characters."""
    runs = []
    for m in PRINTABLE_RUN.finditer(buf):
        s = m.group()
        if len(s) >= min_len:
            runs.append({"offset": m.start(), "text": s.decode("ascii")})
            if len(runs) >= limit:
                break
    # 4-character-code candidates are worth separating: they are the signature
    # of a tag container, while prose strings are a signature of a manifest.
    fourcc = [r for r in runs if len(r["text"]) == 4
              and r["text"].isalpha() and r["text"].islower()]
    return {"count": len(runs), "strings": runs,
            "fourcc_lower_count": len(fourcc)}


# ---------------------------------------------------------------------------
# pass 6: same-offset diff (the F-75 method)
# ---------------------------------------------------------------------------

def diff_bytes(a, b, max_runs=40):
    """Same-offset byte identity plus the run map of the differences.

    Identical-length inputs are the interesting case; a length difference is
    reported rather than silently truncated.
    """
    n = min(len(a), len(b))
    if n == 0:
        return {"identical_fraction": 0.0, "differing": 0}
    diffs = [i for i in range(n) if a[i] != b[i]]
    runs = []
    if diffs:
        start = prev = diffs[0]
        for i in diffs[1:]:
            if i - prev > 1:
                runs.append({"start": start, "end": prev,
                             "length": prev - start + 1})
                start = i
            prev = i
        runs.append({"start": start, "end": prev, "length": prev - start + 1})
    runs_sorted = sorted(runs, key=lambda r: -r["length"])
    return {
        "len_a": len(a),
        "len_b": len(b),
        "compared": n,
        "same_length": len(a) == len(b),
        "identical_bytes": n - len(diffs),
        "identical_fraction": round((n - len(diffs)) / n, 6),
        "differing": len(diffs),
        "differing_fraction": round(len(diffs) / n, 6),
        "diff_run_count": len(runs),
        "diff_runs": runs,
        "largest_runs": runs_sorted[:max_runs],
        "diff_span": ([min(diffs), max(diffs)] if diffs else None),
        "all_diffs_within_span": (
            bool(diffs) and (max(diffs) - min(diffs) + 1) == len(diffs)
        ) if diffs else False,
    }


