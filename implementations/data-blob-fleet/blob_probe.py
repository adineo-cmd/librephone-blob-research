def analyse(buf, name="<memory>", max_stride=256, blocks=16, strings_min=4,
            include_floats=False):
    """Run every pass and return one JSON-serialisable report."""
    report = {
        "file": name,
        "bytes": len(buf),
        "md5": hashlib.md5(buf).hexdigest(),
        "sha256": hashlib.sha256(buf).hexdigest(),
        "factorisation": {
            "value": len(buf),
            "prime_factors": factor_string(len(buf)),
            "divisors": divisors(len(buf))[:48],
            "divisor_count": len(divisors(len(buf))),
        },
        "header": probe_header(buf),
        "stride": detect_stride(buf, max_stride=max_stride),
        "entropy": block_entropy(buf, blocks=blocks),
        "strings": extract_strings(buf, min_len=strings_min),
        "ints": int_pass(buf),
        "floats": float_pass(buf),
        "decompositions": grid_decompositions(len(buf)),
    }
    best = report["stride"]["best_tiling_stride"]
    if best:
        report["stride"]["phase_profile"] = stride_flag_profile(buf, best["stride"])
    if include_floats:
        n = len(buf) // 4
        vals = struct.unpack("<%df" % n, buf[:n * 4]) if n else ()
        report["floats"]["values"] = [float("%.6g" % v) for v in vals[:4096]]
    if len(report["factorisation"]["divisors"]) > 48:
        report["factorisation"]["divisors_truncated"] = True
    return report


def brief_lines(report):
    """Human-readable summary; every number appears in the JSON too."""
    lines = []
    f = report["factorisation"]
    lines.append("%s  %d bytes  md5 %s" % (report["file"], report["bytes"],
                                           report["md5"]))
    lines.append("  factorisation : %s  (%d divisors)"
                 % (f["prime_factors"], f["divisor_count"]))
    h = report["header"]
    lines.append("  head          : %s" % h["first_bytes_hex"])
    lines.append("  ascii         : %s" % h["first_bytes_ascii"])
    if h["magic_hints"]:
        lines.append("  magic hints   : %s" % ", ".join(h["magic_hints"]))
    if h["fourcc_first_kib"]:
        tags = [t["tag"] for t in h["fourcc_first_kib"][:12]]
        lines.append("  4CC in 1 KiB  : %s%s"
                     % (" ".join(tags),
                        " ..." if len(h["fourcc_first_kib"]) > 12 else ""))
    e = report["entropy"]
    lines.append("  entropy       : %.3f bits/byte overall, shape=%s"
                 % (e["overall"], e["shape"]))
    lines.append("  block profile : %s"
                 % " ".join("%.2f" % b["entropy"] for b in e["profile"]))
    s = report["stride"]
    if s["best_tiling_stride"]:
        b = s["best_tiling_stride"]
        lines.append("  best stride   : %d (byte_eq %.3f, word4_eq %.3f, tiles file)"
                     % (b["stride"], b["byte_eq"], b["word4_eq"]))
    top = s["top_by_byte_equality"][:4]
    lines.append("  top strides   : %s"
                 % ", ".join("%d:%.2f" % (t["stride"], t["byte_eq"]) for t in top))
    fl = report["floats"]
    le = fl.get("le") or {}
    if le:
        lines.append("  float32 (LE)  : finite %.3f  in[-1,1] %.3f  "
                     "in[+-1e4] %.3f  denormal %.3f  distinct %.3f"
                     % (le["finite_fraction"], le["in_unit_range"],
                        le["in_physical_range_1e4"], le["denormal_fraction"],
                        le["distinct_fraction"]))
        lines.append("  float verdict : coefficient_table=%s unit_normalised=%s"
                     % (fl["verdict"]["looks_like_coefficient_table"],
                        fl["verdict"]["unit_normalised"]))
    i16 = report["ints"].get("i16")
    if i16:
        lines.append("  i16           : distinct %.3f  zeros %.3f  range %d..%d"
                     % (i16["distinct_fraction"],
                        i16["zeros"] / max(1, i16["samples"]),
                        i16["min"], i16["max"]))
    sp = report["strings"]
    lines.append("  strings       : %d runs (>=%d chars), %d lowercase 4CC"
                 % (sp["count"], len(sp["strings"]) and
                    min(len(x["text"]) for x in sp["strings"]) or 0,
                    sp["fourcc_lower_count"]))
    return lines


def main(argv=None):
    ap = argparse.ArgumentParser(
        description="clean-room structural analyser for opaque data blobs",
        epilog="Reports measurements only; asserts no undetected structure.")
    ap.add_argument("file", help="input blob")
    ap.add_argument("--json", metavar="OUT", help="write the full report as JSON")
    ap.add_argument("--brief", action="store_true", help="summary only")
    ap.add_argument("--floats", action="store_true",
                    help="include up to 4096 binary32 samples in the JSON")
    ap.add_argument("--diff", metavar="OTHER",
                    help="second file: report same-offset byte identity")
    ap.add_argument("--max-stride", type=int, default=256,
                    help="largest record stride to probe (default 256)")
    ap.add_argument("--strings-min", type=int, default=4,
                    help="minimum printable run length (default 4)")
    ap.add_argument("--blocks", type=int, default=16,
                    help="entropy profile block count (default 16)")
    args = ap.parse_args(argv)

    try:
        with open(args.file, "rb") as fh:
            buf = fh.read()
    except OSError as exc:
        print("blob_probe: cannot read %s: %s" % (args.file, exc),
              file=sys.stderr)
        return 2

    report = analyse(buf, name=os.path.basename(args.file),
                     max_stride=args.max_stride, blocks=args.blocks,
                     strings_min=args.strings_min,
                     include_floats=args.floats)

    if args.diff:
        try:
            with open(args.diff, "rb") as fh:
                other = fh.read()
        except OSError as exc:
            print("blob_probe: cannot read %s: %s" % (args.diff, exc),
                  file=sys.stderr)
            return 2
        report["diff"] = diff_bytes(buf, other)
        report["diff"]["other_file"] = os.path.basename(args.diff)

    if args.json:
        with open(args.json, "w", encoding="utf-8") as fh:
            json.dump(report, fh, indent=2, sort_keys=False)
            fh.write("\n")

    if args.brief or not args.json:
        for line in brief_lines(report):
            print(line)
        if "diff" in report:
            d = report["diff"]
            print("  diff vs %s: %.4f%% same-offset identical, %d runs, span %s"
                  % (d["other_file"], 100 * d["identical_fraction"],
                     d["diff_run_count"], d["diff_span"]))
    return 0


if __name__ == "__main__":
    sys.exit(main())
