def float_pass(buf, width=4):
    """Read `buf` as little- and big-endian IEEE-754 binary32 and score both.

    The score that matters for a coefficient table is `in_unit_range`: the
    fraction of finite samples in [-1, 1].  A normalised HRIR/HRTF table sits
    high on that.  A tag/integer file read as float produces denormals
    (|x| < 1e-38) and values near 1e30, so `denormal_fraction` is high and
    `in_unit_range` is near zero by coincidence only.
    """
    out = {}
    for endian, label in (("<", "le"), (">", "be")):
        n = len(buf) // width
        if n == 0:
            out[label] = None
            continue
        vals = struct.unpack("%s%d%s" % (endian, n, "f" if width == 4 else "d"),
                             buf[:n * width])
        finite = [v for v in vals if math.isfinite(v)]
        nf = len(finite)
        if nf:
            absvals = sorted(abs(v) for v in finite)
            median = absvals[nf // 2]
            in_unit = sum(1 for v in finite if -1.0 <= v <= 1.0) / nf
            in_phys = sum(1 for v in finite if -1e4 <= v <= 1e4) / nf
            denorm = sum(1 for v in finite if 0.0 < abs(v) < 1.1754944e-38) / nf
            distinct = len(set(finite))
        else:
            median = 0.0
            in_unit = in_phys = denorm = 0.0
            distinct = 0
        out[label] = {
            "samples": n,
            "finite_fraction": round(nf / n, 4),
            "in_unit_range": round(in_unit, 4),
            "in_physical_range_1e4": round(in_phys, 4),
            "denormal_fraction": round(denorm, 4),
            "distinct_values": distinct,
            "distinct_fraction": round(distinct / n, 4),
            "median_abs": float("%.6g" % median),
            "min": float("%.6g" % min(finite)) if nf else None,
            "max": float("%.6g" % max(finite)) if nf else None,
            "first8": [float("%.6g" % v) for v in vals[:8]],
        }
    # convenience verdicts, both honest about being heuristics
    le = out.get("le") or {}
    out["verdict"] = {
        "looks_like_coefficient_table": bool(
            le.get("finite_fraction", 0) > 0.999
            and le.get("in_physical_range_1e4", 0) > 0.99
            and le.get("denormal_fraction", 1) < 0.01
        ),
        "unit_normalised": bool(le.get("in_unit_range", 0) > 0.9),
        "note": ("a binary32 coefficient table is finite, non-denormal and in a "
                 "narrow physical range; an integer/tag file is not"),
    }
    return out


def int_pass(buf):
    """Histogram the obvious integer interpretations.

    A tag container has a handful of distinct 32-bit words with a dominant
    zero and a dominant small-integer value; a coefficient table is close to
    uniformly distributed.  `distinct_fraction` is the discriminator.
    """
    out = {}
    for width, code in ((1, "B"), (2, "H"), (4, "I")):
        n = len(buf) // width
        if n == 0:
            continue
        vals = struct.unpack("<%d%s" % (n, code), buf[:n * width])
        counts = collections.Counter(vals)
        out["u%d" % (width * 8)] = {
            "samples": n,
            "distinct": len(counts),
            "distinct_fraction": round(len(counts) / n, 4),
            "zeros": counts.get(0, 0),
            "zero_fraction": round(counts.get(0, 0) / n, 4),
            "min": min(vals),
            "max": max(vals),
            "top8": counts.most_common(8),
        }
    # signed 16-bit is the other realistic audio container
    n = len(buf) // 2
    if n:
        vals = struct.unpack("<%dh" % n, buf[:n * 2])
        counts = collections.Counter(vals)
        out["i16"] = {
            "samples": n,
            "distinct": len(counts),
            "distinct_fraction": round(len(counts) / n, 4),
            "zeros": counts.get(0, 0),
            "min": min(vals),
            "max": max(vals),
            "top8": counts.most_common(8),
        }
    return out


